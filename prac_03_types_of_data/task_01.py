# Задание 1

# Создаем переменные
a = 42
b = 3.14159
c = "Hello, Python!"
d = True
e = [1, 2, 3]
f = (4, 5, 6)
g = {"name": "Alice", "age": 30}
h = {7, 8, 9}
i = None

# Выводим типы переменных
print(type(a))  # целое число
print(type(b))  # число с плавающей точкой
print(type(c))  # строка
print(type(d))  # булев тип
print(type(e))  # список
print(type(f))  # кортеж
print(type(g))  # словарь
print(type(h))  # множество
print(type(i))  # тип данных None ("ничего")
